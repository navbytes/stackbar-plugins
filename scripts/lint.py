#!/usr/bin/env python3
"""House rules for every plugin, and the generated plugin table in README.md.

    python3 scripts/lint.py                  check every plugin and the README table
    python3 scripts/lint.py --write-readme   regenerate the README table
    python3 scripts/lint.py --base origin/main   also require a version bump for
                                             plugins whose source changed since that ref
"""
import json
import os
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATEGORIES = ["System", "Developer", "Network", "Monitoring", "Productivity"]
ID_PREFIX = "io.navbytes.stackbar.plugins."
# Plugins that shipped inside Stackbar before they moved here keep their ids,
# so settings, storage and approvals (all keyed by id) carry over.
LEGACY_IDS = {
    "io.navbytes.stackbar.clipboard",
    "io.navbytes.stackbar.pr-cockpit",
    "io.navbytes.stackbar.quicklinks",
    "io.navbytes.stackbar.snippets",
    "io.navbytes.stackbar.stay-awake",
    "io.navbytes.stackbar.up-next",
}
# Apple's on-device language frameworks do no I/O of their own, so they
# don't get around the sandbox or the host calls.
ALLOWED_IMPORTS = {"StackbarKit", "Foundation", "NaturalLanguage", "Translation"}
README_START = "<!-- plugins:start (generated by scripts/lint.py --write-readme) -->"
README_END = "<!-- plugins:end -->"


def plugins():
    for category in CATEGORIES:
        folder = ROOT / category
        if not folder.is_dir():
            continue
        for directory in sorted(p for p in folder.iterdir() if p.is_dir()):
            yield category, directory


def stackbarctl():
    """check.sh passes the stackbarctl it built; run alone, lint builds the same one."""
    if "STACKBARCTL" in os.environ:
        return os.environ["STACKBARCTL"]
    subprocess.run(["swift", "build", "-c", "release", "--product", "stackbarctl"], cwd=ROOT, check=True, stdout=sys.stderr)
    bin_path = subprocess.run(["swift", "build", "-c", "release", "--show-bin-path"], cwd=ROOT, check=True, capture_output=True, text=True)
    return f"{bin_path.stdout.strip()}/stackbarctl"


def manifest_report(ctl, source_file):
    """The manifest the plugin declares, from `stackbarctl manifest --json`:
    {"manifest", "problems", "publishingProblems"}. None if it doesn't build."""
    result = subprocess.run([ctl, "manifest", str(source_file), "--json"], cwd=ROOT, capture_output=True, text=True)
    return json.loads(result.stdout) if result.returncode == 0 else None


def version_tuple(text):
    return tuple(int(part) for part in re.findall(r"\d+", text or "0"))


def lint(ctl, base=None):
    problems = []
    rows = []
    seen_ids = {}
    for category, directory in plugins():
        name = directory.name
        where = f"{category}/{name}"
        source_file = directory / f"{name}.swift"
        if not source_file.is_file():
            problems.append(f"{where}: needs {name}.swift (the folder and the file share a name)")
            continue
        others = [p.name for p in directory.iterdir() if p.name not in {f"{name}.swift", "README.md"} and not p.name.startswith(".")]
        if others:
            problems.append(f"{where}: only {name}.swift and README.md belong here, found {', '.join(sorted(others))}")
        if not (directory / "README.md").is_file():
            problems.append(f"{where}: needs a README.md (what it does, what it needs, its settings)")
        if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name):
            problems.append(f"{where}: folder names are UpperCamelCase, like WorldClock")
        source = source_file.read_text()
        for module in re.findall(r"^\s*(?:@\w+\s+)*import\s+(\w+)", source, re.M):
            if module not in ALLOWED_IMPORTS:
                problems.append(f"{where}: imports {module}; plugins import only StackbarKit and Foundation (plus NaturalLanguage and Translation)")
        if re.search(r"(?<![\w.])print\(", source):
            problems.append(f"{where}: uses print(); show it in a view or log through the host instead")
        for banned in ("URLSession", "Process(", "FileManager"):
            if banned in source:
                problems.append(f"{where}: uses {banned.rstrip('(')}; plugins are sandboxed, go through Stackbar.* host calls")
        report = manifest_report(ctl, source_file)
        if report is None:
            problems.append(f"{where}: can't read its manifest; run stackbarctl manifest {where}/{name}.swift")
            continue
        manifest = report["manifest"]
        plugin_id, version, summary = manifest["id"], manifest["version"], manifest.get("summary")
        # The version format, summary and minimumStackbar every published plugin needs.
        problems += [f"{where}: {problem}" for problem in report["publishingProblems"]]
        if not (plugin_id.startswith(ID_PREFIX) or plugin_id in LEGACY_IDS):
            problems.append(f"{where}: manifest id must start with {ID_PREFIX}")
        elif plugin_id in seen_ids:
            problems.append(f"{where}: id {plugin_id} is also used by {seen_ids[plugin_id]}")
        else:
            seen_ids[plugin_id] = where
        readme = directory / "README.md"
        if readme.is_file() and f"## What's new in {version}\n" not in readme.read_text():
            problems.append(f"{where}: README.md needs a \"## What's new in {version}\" section; the store shows it on the Update button")
        if base:
            old = git_show(base, f"{category}/{name}/{name}.swift")
            if old is not None and old != source:
                old_version = base_version(ctl, name, old)
                if old_version is None:
                    print(f"warning: {where}: can't build its source at {base}, so its version bump isn't checked")
                elif version_tuple(version) <= version_tuple(old_version):
                    problems.append(f"{where}: source changed since {base} but version is still {version}; raise it")
        rows.append(f"| [{manifest['name']}]({category}/{name}) | {category} | {summary or ''} |")
    return problems, rows


def base_version(ctl, name, source):
    """The version an older source declared, built from a copy under the
    plugin's own file name, which stackbarctl names the helper after."""
    with tempfile.TemporaryDirectory() as directory:
        copy = pathlib.Path(directory) / f"{name}.swift"
        copy.write_text(source)
        report = manifest_report(ctl, copy)
    return report and report["manifest"]["version"]


def git_show(ref, path):
    result = subprocess.run(["git", "show", f"{ref}:{path}"], cwd=ROOT, capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def readme_with(rows):
    readme = (ROOT / "README.md").read_text()
    table = "\n".join(["| Plugin | Category | What it does |", "| --- | --- | --- |", *rows])
    start, end = readme.index(README_START), readme.index(README_END)
    return readme[: start + len(README_START)] + "\n\n" + table + "\n\n" + readme[end:]


def main(argv):
    base = argv[argv.index("--base") + 1] if "--base" in argv else None
    problems, rows = lint(stackbarctl(), base)
    expected = readme_with(rows)
    if "--write-readme" in argv:
        (ROOT / "README.md").write_text(expected)
    elif expected != (ROOT / "README.md").read_text():
        problems.append("README.md's plugin table is stale; run python3 scripts/lint.py --write-readme")
    revoked = json.loads((ROOT / "revoked.json").read_text())
    for entry in revoked:
        if not {"id", "reason"} <= entry.keys():
            problems.append(f"revoked.json: every entry needs id and reason: {entry}")
    for problem in problems:
        print(f"::error::{problem}" if "GITHUB_ACTIONS" in os.environ else f"error: {problem}")
    print(f"{len(rows)} plugins, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
