#!/usr/bin/env python3
"""House rules for every plugin, and the generated plugin table in README.md.

    python3 scripts/lint.py                  check every plugin and the README table
    python3 scripts/lint.py --write-readme   regenerate the README table
    python3 scripts/lint.py --base origin/main   also require a version bump for
                                             plugins whose source changed since that ref
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATEGORIES = ["System", "Developer", "Network", "Monitoring", "Productivity"]
ID_PREFIX = "io.navbytes.stackbar.plugins."
ALLOWED_IMPORTS = {"StackbarKit", "Foundation"}
README_START = "<!-- plugins:start (generated by scripts/lint.py --write-readme) -->"
README_END = "<!-- plugins:end -->"


def plugins():
    for category in CATEGORIES:
        folder = ROOT / category
        if not folder.is_dir():
            continue
        for directory in sorted(p for p in folder.iterdir() if p.is_dir()):
            yield category, directory


def manifest_field(source: str, name: str):
    block = re.search(r"static let manifest = Manifest\((.*?)\n    \)", source, re.S)
    if not block:
        return None
    match = re.search(rf'\b{name}:\s*"([^"]*)"', block.group(1))
    return match.group(1) if match else None


def version_tuple(text):
    return tuple(int(part) for part in re.findall(r"\d+", text or "0"))


def lint(base=None):
    problems = []
    rows = []
    seen_ids = {}
    for category, directory in plugins():
        name = directory.name
        where = f"{category}/{name}"
        source_file = directory / f"{name}.swift"
        if not source_file.is_file():
            problems.append(f"{where}: needs {name}.swift (the folder and the file share a name)")
            continue
        others = [p.name for p in directory.iterdir() if p.name not in {f"{name}.swift", "README.md"} and not p.name.startswith(".")]
        if others:
            problems.append(f"{where}: only {name}.swift and README.md belong here, found {', '.join(sorted(others))}")
        if not (directory / "README.md").is_file():
            problems.append(f"{where}: needs a README.md (what it does, what it needs, its settings)")
        if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", name):
            problems.append(f"{where}: folder names are UpperCamelCase, like WorldClock")
        source = source_file.read_text()
        for module in re.findall(r"^\s*(?:@\w+\s+)*import\s+(\w+)", source, re.M):
            if module not in ALLOWED_IMPORTS:
                problems.append(f"{where}: imports {module}; plugins import only StackbarKit and Foundation")
        if re.search(r"(?<![\w.])print\(", source):
            problems.append(f"{where}: uses print(); show it in a view or log through the host instead")
        for banned in ("URLSession", "Process(", "FileManager"):
            if banned in source:
                problems.append(f"{where}: uses {banned.rstrip('(')}; plugins are sandboxed, go through Stackbar.* host calls")
        plugin_id = manifest_field(source, "id")
        version = manifest_field(source, "version")
        summary = manifest_field(source, "summary")
        display = manifest_field(source, "name") or name
        if not plugin_id or not plugin_id.startswith(ID_PREFIX):
            problems.append(f"{where}: manifest id must start with {ID_PREFIX}")
        elif plugin_id in seen_ids:
            problems.append(f"{where}: id {plugin_id} is also used by {seen_ids[plugin_id]}")
        else:
            seen_ids[plugin_id] = where
        if not version or not re.fullmatch(r"\d+\.\d+\.\d+", version):
            problems.append(f"{where}: manifest needs version: \"x.y.z\"")
        if not summary:
            problems.append(f"{where}: manifest needs a summary (the store shows it on the card)")
        if not manifest_field(source, "minimumStackbar"):
            problems.append(f"{where}: manifest needs minimumStackbar")
        if base and version:
            old = git_show(base, f"{category}/{name}/{name}.swift")
            if old is not None and old != source:
                old_version = manifest_field(old, "version")
                if version_tuple(version) <= version_tuple(old_version):
                    problems.append(f"{where}: source changed since {base} but version is still {version}; raise it")
        rows.append(f"| [{display}]({category}/{name}) | {category} | {summary or ''} |")
    return problems, rows


def git_show(ref, path):
    result = subprocess.run(["git", "show", f"{ref}:{path}"], cwd=ROOT, capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def readme_with(rows):
    readme = (ROOT / "README.md").read_text()
    table = "\n".join(["| Plugin | Category | What it does |", "| --- | --- | --- |", *rows])
    start, end = readme.index(README_START), readme.index(README_END)
    return readme[: start + len(README_START)] + "\n\n" + table + "\n\n" + readme[end:]


def main(argv):
    base = argv[argv.index("--base") + 1] if "--base" in argv else None
    problems, rows = lint(base)
    expected = readme_with(rows)
    if "--write-readme" in argv:
        (ROOT / "README.md").write_text(expected)
    elif expected != (ROOT / "README.md").read_text():
        problems.append("README.md's plugin table is stale; run python3 scripts/lint.py --write-readme")
    revoked = json.loads((ROOT / "revoked.json").read_text())
    for entry in revoked:
        if not {"id", "reason"} <= entry.keys():
            problems.append(f"revoked.json: every entry needs id and reason: {entry}")
    for problem in problems:
        print(f"::error::{problem}" if "GITHUB_ACTIONS" in __import__("os").environ else f"error: {problem}")
    print(f"{len(rows)} plugins, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
